"""Exercise the portable size check against real, isolated Git indexes."""

import hashlib
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch


SCRIPT = Path(__file__).with_name("check_staged_file_size.py")
spec = importlib.util.spec_from_file_location("staged_size", SCRIPT)
checker = importlib.util.module_from_spec(spec)
spec.loader.exec_module(checker)


class StagedSizeTests(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory(prefix="develop-staged-size-")
        self.addCleanup(self.directory.cleanup)
        self.root = Path(self.directory.name)
        self.env = {key: value for key, value in os.environ.items()
                    if not key.startswith("GIT_")}
        self.env.update(GIT_CONFIG_NOSYSTEM="1", GIT_CONFIG_GLOBAL=os.devnull,
                        GIT_TERMINAL_PROMPT="0", GIT_OPTIONAL_LOCKS="0")
        self.git("init", "-q")

    def git(self, *args, data=None):
        return subprocess.run(["git", *args], cwd=self.root, env=self.env,
                              input=data, stdout=subprocess.PIPE,
                              stderr=subprocess.PIPE, check=True).stdout

    def stage(self, name, content):
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
        self.git("add", "--", name)
        return path

    def profile(self, **values):
        path = self.root / "size-profile.json"
        path.write_text(json.dumps(dict(schema_version=1, **values)), encoding="utf-8")
        return path.name

    def run_check(self, *args, expected=0, cwd=None, env=None):
        result = subprocess.run([sys.executable, "-I", str(SCRIPT), *args],
                                cwd=cwd or self.root, env=self.env if env is None else env,
                                stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                text=True, timeout=20)
        self.assertEqual(result.returncode, expected, result.stderr)
        self.assertEqual(result.stdout, "")
        return result.stderr

    def test_default_boundary_and_read_only_index(self):
        self.stage("exact.txt", b"x" * 20000)
        self.run_check()
        file = self.stage("too-large.txt", b"x" * 20001)
        index = (self.root / ".git/index").read_bytes()
        file.write_bytes(b"small unstaged replacement")
        before = file.read_bytes()
        message = self.run_check(expected=1)
        self.assertIn('"too-large.txt": 20,001 bytes', message)
        self.assertNotIn('"exact.txt":', message)
        self.assertEqual((self.root / ".git/index").read_bytes(), index)
        self.assertEqual(file.read_bytes(), before)

    def test_large_unstaged_content_does_not_fail(self):
        self.stage("small.txt", b"small").write_bytes(b"x" * 30000)
        self.run_check()

    def test_generated_binary_private_and_lockfile_exclusions(self):
        for name in (".env", ".env.production", "private/auth.json", "credentials.json",
                     ".npmrc", ".netrc", "secret.key", "secret.pem", "image.PNG",
                     "node_modules/pkg/a.js", "dist/bundle.js", "uv.lock", "go.sum",
                     "zz_generated.go", "service.pb.go", "app.min.js"):
            self.stage(name, b"x" * 20001)
        self.stage("binary.dat", b"\0" + b"x" * 20000)
        self.stage("generated.py", b"# Code generated by a tool. DO NOT EDIT\n" + b"x" * 20001)
        self.stage("other.py", b"# @generated\n" + b"x" * 20001)
        self.run_check()

    def test_staged_attributes_not_dirty_working_tree(self):
        attrs = self.stage(".gitattributes", b"generated.txt linguist-generated=true\nvendored.txt linguist-vendored\n")
        self.stage("generated.txt", b"x" * 20001)
        self.stage("vendored.txt", b"x" * 20001)
        attrs.write_text("generated.txt -linguist-generated\nvendored.txt linguist-vendored\n", encoding="utf-8")
        self.run_check()
        self.git("add", "--", ".gitattributes")
        attrs.write_text("generated.txt linguist-generated\n", encoding="utf-8")
        self.run_check(expected=1)

    def test_submodule_symlink_deletion_and_executable_modes(self):
        blob = self.git("hash-object", "-w", "--stdin", data=b"x" * 20001).strip().decode()
        self.git("update-index", "--add", "--cacheinfo", f"120000,{blob},link")
        self.git("update-index", "--add", "--cacheinfo", f"160000,{'1' * 40},child")
        self.run_check()
        self.git("update-index", "--add", "--cacheinfo", f"100755,{blob},executable")
        self.assertIn('"executable"', self.run_check(expected=1))
        self.git("update-index", "--force-remove", "executable")
        self.run_check()

    def test_profile_paths_prefix_boundaries_and_cli_precedence(self):
        self.stage("private/notes.txt", b"x" * 20001)
        self.stage("private-other/notes.txt", b"x" * 21000)
        self.stage("selected.txt", b"x" * 20001)
        profile = self.profile(max_bytes=21000, exclude_paths=["selected.txt"],
                               exclude_prefixes=["private"])
        self.run_check("--profile", profile)
        message = self.run_check("--profile", profile, "--max-bytes", "20000", expected=1)
        self.assertIn('"private-other/notes.txt"', message)
        self.assertNotIn('"private/notes.txt"', message)
        self.assertNotIn('"selected.txt"', message)

    def test_explicit_profile_and_repo_from_unrelated_directory(self):
        self.stage("large.txt", b"x" * 20001)
        profile = self.profile(exclude_paths=["large.txt"])
        self.run_check(expected=1)  # No implicit profile discovery.
        with tempfile.TemporaryDirectory(prefix="develop-unrelated-") as unrelated:
            self.run_check("--repo", str(self.root), "--profile", profile, cwd=unrelated)

    def test_small_custom_threshold_reads_only_available_bytes(self):
        self.stage("exact.txt", b"x" * 4)
        self.stage("large.txt", b"x" * 5)
        self.assertIn('"large.txt": 5 bytes', self.run_check("--max-bytes", "4", expected=1))

    def test_explicit_repo_rejects_foreign_git_selectors_and_index(self):
        self.stage("large.txt", b"x" * 20001)
        profile = self.profile()
        with tempfile.TemporaryDirectory(prefix="develop-other-repo-") as other:
            foreign = Path(other)
            def other_git(*args):
                subprocess.run(["git", *args], cwd=foreign, env=self.env,
                               stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True)
            other_git("init", "-q")
            (foreign / "small.txt").write_bytes(b"small")
            other_git("add", "--", "small.txt")
            # A valid foreign profile must never redirect explicit selection.
            (foreign / profile).write_text('{"schema_version":1}', encoding="utf-8")
            overrides = [
                dict(GIT_DIR=str(foreign / ".git"), GIT_WORK_TREE=str(foreign)),
                dict(GIT_DIR=str(foreign / ".git"), GIT_WORK_TREE=str(self.root)),
                dict(GIT_INDEX_FILE=str(foreign / ".git/index"),
                     GIT_ALTERNATE_OBJECT_DIRECTORIES=str(foreign / ".git/objects")),
                dict(GIT_COMMON_DIR=str(foreign / ".git")),
            ]
            for override in overrides:
                with self.subTest(override=override):
                    message = self.run_check("--repo", str(self.root), "--profile", profile,
                                             env={**self.env, **override}, expected=1)
                    self.assertIn("Unable to inspect", message)

    def test_explicit_repo_preserves_selected_hook_index(self):
        self.stage("large.txt", b"x" * 20001)
        original = (self.root / ".git/index").read_bytes()
        alternate = self.root / ".git/next-index"
        alternate.write_bytes(original)
        small = self.git("hash-object", "-w", "--stdin", data=b"small").strip().decode()
        environment = {**self.env, "GIT_INDEX_FILE": str(alternate),
                       "GIT_DIR": str(self.root / ".git"), "GIT_WORK_TREE": str(self.root)}
        subprocess.run(["git", "update-index", "--cacheinfo", f"100644,{small},large.txt"],
                       cwd=self.root, env=environment, check=True)
        with tempfile.TemporaryDirectory(prefix="develop-hook-cwd-") as unrelated:
            self.run_check("--repo", str(self.root), "--profile", self.profile(),
                           env=environment, cwd=unrelated)
        self.assertEqual((self.root / ".git/index").read_bytes(), original)
        self.run_check("--repo", str(self.root), expected=1)

    def test_external_index_requires_current_context_invocation(self):
        self.stage("small.txt", b"small")
        with tempfile.TemporaryDirectory(prefix="develop-external-index-") as temporary:
            alternate = Path(temporary) / "index"
            alternate.write_bytes((self.root / ".git/index").read_bytes())
            environment = {**self.env, "GIT_INDEX_FILE": str(alternate)}
            self.run_check(env=environment)
            self.run_check("--repo", str(self.root), env=environment, expected=1)

    def test_explicit_repo_supports_linked_worktree_hook_index(self):
        self.stage("base.txt", b"base")
        self.git("-c", "user.name=Fixture", "-c", "user.email=fixture@example.invalid",
                 "-c", "commit.gpgsign=false", "commit", "-qm", "Fixture")
        with tempfile.TemporaryDirectory(prefix="develop-linked-worktree-") as temporary:
            linked = Path(temporary) / "linked"
            self.git("worktree", "add", "--detach", str(linked), "HEAD")
            (linked / "large.txt").write_bytes(b"x" * 20001)
            self.git("-C", str(linked), "add", "--", "large.txt")
            self.run_check("--repo", str(linked), expected=1)
            git_dir = Path(os.fsdecode(self.git("-C", str(linked), "rev-parse",
                                               "--absolute-git-dir").strip()))
            alternate = git_dir / "next-index"
            alternate.write_bytes((git_dir / "index").read_bytes())
            small = self.git("hash-object", "-w", "--stdin", data=b"small").strip().decode()
            environment = {**self.env, "GIT_INDEX_FILE": str(alternate),
                           "GIT_DIR": str(git_dir), "GIT_WORK_TREE": str(linked)}
            subprocess.run(["git", "update-index", "--cacheinfo", f"100644,{small},large.txt"],
                           cwd=linked, env=environment, check=True)
            self.run_check("--repo", str(linked), env=environment)

    def test_unusual_paths_are_unambiguous_in_report(self):
        names = ['line\nbreak.txt', 'tab\tname.txt', 'quote"name.txt', '-leading.txt']
        if os.name == "nt":
            names = ['space name.txt', '-leading.txt']
        for name in names:
            self.stage(name, b"x" * 20001)
        message = self.run_check(expected=1)
        for name in names:
            self.assertIn(json.dumps(name), message)

    def test_invalid_profiles_fail_closed(self):
        profile = self.root / "size-profile.json"
        cases = [b"{", b"[]", b'{"schema_version":2}',
                 b'{"schema_version":true}', b'{"schema_version":1,"unknown":[]}',
                 b'{"schema_version":1,"max_bytes":false}',
                 b'{"schema_version":1,"max_bytes":0}',
                 b'{"schema_version":1,"exclude_paths":"file"}',
                 b'{"schema_version":1,"exclude_paths":["../file"]}',
                 b'{"schema_version":1,"exclude_prefixes":["/tmp"]}',
                 b'{"schema_version":1,"exclude_paths":["a//b"]}',
                 b'{"schema_version":1,"schema_version":1}',
                 b" " * 65537, b"\xff"]
        for content in cases:
            with self.subTest(content=content[:100]):
                profile.write_bytes(content)
                self.run_check("--profile", profile.name, expected=1)
        self.run_check("--profile", "../outside.json", expected=1)
        self.run_check("--profile", "missing.json", expected=1)
        self.run_check("--max-bytes", "0", expected=2)

    def test_profile_symlinks_are_rejected(self):
        target = self.root / self.profile()
        link = self.root / "profile-link.json"
        try:
            link.symlink_to(target)
        except OSError:
            self.skipTest("symlink creation is unavailable on this host")
        self.run_check("--profile", link.name, expected=1)

    def test_unmerged_index_fails_closed(self):
        blob = self.git("hash-object", "-w", "--stdin", data=b"small").strip()
        self.git("update-index", "--index-info", data=b"100644 " + blob + b" 1\tconflict\n")
        self.run_check(expected=1)

    def test_non_repository_fails_closed(self):
        with tempfile.TemporaryDirectory(prefix="develop-no-repo-") as unrelated:
            self.run_check(cwd=unrelated, expected=1)

    def test_protected_profile_exclusions_precede_blob_access(self):
        # Missing objects would make any accidental size/content read fail.
        absent = "1" * 40
        self.git("update-index", "--add", "--cacheinfo", f"100644,{absent},protected/doc.md")
        self.git("update-index", "--add", "--cacheinfo", f"100644,{absent},private/state")
        self.git("update-index", "--add", "--cacheinfo", f"100644,{absent},.env")
        self.run_check("--profile", self.profile(exclude_paths=["protected/doc.md"],
                                                exclude_prefixes=["private"]))
        self.run_check(expected=1)

    def test_blob_prefix_is_bounded(self):
        self.stage("huge.txt", b"x" * (2 * 1024 * 1024))
        oid = self.git("rev-parse", ":huge.txt").strip()
        with patch.dict(os.environ, self.env, clear=True):
            previous = Path.cwd()
            try:
                os.chdir(self.root)
                prefix = checker.blob_prefix(oid, 2 * 1024 * 1024)
            finally:
                os.chdir(previous)
        self.assertEqual(len(prefix), 8192)
        self.assertEqual(hashlib.sha256(prefix).digest(), hashlib.sha256(b"x" * 8192).digest())

    def test_marker_outside_probe_does_not_exempt_authored_content(self):
        self.stage("authored.txt", b"x" * 8192 + b"\n# @generated\n" + b"x" * 20001)
        self.run_check(expected=1)


if __name__ == "__main__":
    unittest.main()
